"""Generates src/lt_hb_prefix.h, which renames every HarfBuzz identifier with macros.

Unity's own player links a copy of HarfBuzz. On platforms where plugins link statically
(iOS, web) ours would collide with it, and hidden visibility does not help there. The
header is force-included when compiling, so the HarfBuzz sources stay unmodified.

usage: python gen_hb_prefix.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "third_party", "harfbuzz", "src")
TOKEN = re.compile(r"\b_?hb_[A-Za-z0-9_]+\b")
MACRO = re.compile(r"^[ \t]*#[ \t]*define[ \t]+(_?hb_[A-Za-z0-9_]+)", re.M)

# Namespaces and other global names HarfBuzz defines without the hb_ prefix.
EXTRA = ["OT", "AAT", "CFF", "graph", "TupleVariationData", "cff1_path_param_t", "bounds_t", "data_destroy_arabic", "endchar_str", "minus_1",
         "_hb_Null_AAT_Lookup", "_hb_Null_AAT_SettingName", "_hb_Null_OT_ClipRecord", "_hb_Null_OT_CmapSubtableLongGroup", "_hb_Null_OT_Index",
         "_hb_Null_OT_LangSys", "_hb_Null_OT_VarIdx", "_hb_Null_hb_buffer_t", "_hb_Null_hb_draw_funcs_t", "_hb_Null_hb_paint_funcs_t"]

# Functions HarfBuzz also defines as same-named macros, so no rename can reach them. They are trivial
# and identical in any copy, so weak definitions let whichever copy the linker keeps serve both.
WEAK = ["hb_color_get_alpha", "hb_color_get_red", "hb_color_get_green", "hb_color_get_blue", "hb_glyph_info_get_glyph_flags"]


def main():
    tokens = set()
    macros = set()  # Redefining these would replace the rename; they leave no linker symbols anyway.
    for directory, _, files in os.walk(SRC):
        for name in files:
            # Test programs define stand-ins that the library never sees.
            if name.startswith(("test", "main")):
                continue
            if name.endswith((".h", ".hh", ".cc", ".rl")):
                with open(os.path.join(directory, name), encoding="utf-8", errors="replace") as f:
                    text = f.read()
                tokens.update(TOKEN.findall(text))
                macros.update(MACRO.findall(text))
    with open(os.path.join(ROOT, "src", "lettera_native.cpp"), encoding="utf-8") as f:
        tokens.update(TOKEN.findall(f.read()))
    tokens -= macros
    with open(os.path.join(ROOT, "src", "lt_hb_prefix.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_hb_prefix.py. Do not edit.\n#pragma once\n")
        for token in sorted(tokens):
            f.write(f"#define {token} lt_{token}\n")
        for name in EXTRA:
            f.write(f"#define {name} lt_{name}\n")
        for name in WEAK:
            f.write(f"#pragma weak {name}\n")
    print(len(tokens), "identifiers")


if __name__ == "__main__":
    main()
