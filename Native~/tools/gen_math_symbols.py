"""Generates Runtime/Math/LetteraMathSymbols.g.cs from math_symbols.tsv: command names of TeX's plain symbols and amssymb's, taken from public lists and Unicode names.

Each row: name, code point (hex), class. Classes: O ord, P large operator, B binary, R relation, A open, C close, U punctuation.

usage: python gen_math_symbols.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.dirname(os.path.abspath(__file__))
rows = []
seen = set()
for line in open(os.path.join(HERE, "math_symbols.tsv"), encoding="utf-8"):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    name, code, cls = line.split()
    if name in seen:
        raise SystemExit("twice: " + name)
    seen.add(name)
    int(code, 16)
    if cls not in "OPBRACU":
        raise SystemExit("class: " + line)
    rows.append((name, code, cls))
rows.sort()
data = ";".join(f"{n} {c} {k}" for n, c, k in rows)
out = os.path.join(ROOT, "Runtime", "Math", "LetteraMathSymbols.g.cs")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by Native~/tools/gen_math_symbols.py from math_symbols.tsv. Do not edit.\n")
    f.write("namespace FirstSymbol.Lettera\n{\n    internal static partial class LetteraMathSymbols\n    {\n")
    f.write(f"        internal const int Count = {len(rows)};\n")
    f.write(f'        const string Table = "{data}";\n')
    f.write("    }\n}\n")
print(len(rows), "symbols")
